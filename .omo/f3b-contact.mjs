import { chromium } from "@playwright/test"
const BASE = "http://127.0.0.1:3000"
const browser = await chromium.launch({ executablePath: "/etc/profiles/per-user/tom/bin/chromium", args: ["--no-sandbox"] })
const c = await browser.newContext()
const page = await c.newPage()
await page.goto(`${BASE}/contact`, { waitUntil: "load" })
await page.waitForLoadState("networkidle")
await page.fill('input[name="name"]', "F3 QA")
await page.fill('input[name="email"]', "qa@example.com")
await page.fill('textarea[name="message"]', "F3 hydration interactivity probe.")
await page.click('button[type="submit"]')
await page.waitForSelector('[role="status"]', { timeout: 15000 })
const txt = await page.locator('[role="status"]').first().innerText()
console.log(`CONTACT success: role=status text=${JSON.stringify(txt.slice(0,60))}`)
const done = await page.getByRole("button", { name: "Done" }).count()
console.log(`CONTACT Done button count=${done}`)
// invalid email path
await page.goto(`${BASE}/contact`, { waitUntil: "load" })
await page.waitForLoadState("networkidle")
await page.fill('input[name="name"]', "X")
await page.fill('input[name="email"]', "bad")
await page.fill('textarea[name="message"]', "y")
await page.click('button[type="submit"]')
await page.waitForSelector('#email-error', { timeout: 10000 })
console.log("CONTACT invalid-email error:", JSON.stringify(await page.locator('#email-error').innerText()))
await browser.close()
