export function coverKeyForSlug(slug: string): ProjectCoverKey {
  const normalizedSlug = slug.toLowerCase()

  for (const [pattern, key] of coverRules) {
    if (pattern.test(normalizedSlug)) return key
  }
  return "archive"
}
